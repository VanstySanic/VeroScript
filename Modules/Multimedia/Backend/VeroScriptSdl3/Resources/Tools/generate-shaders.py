"""Regenerate embedded 2D shaders; runtime builds need no shader compiler.

Requires Windows SDK fxc and glslangValidator (native or --wsl).
"""
import argparse
import re
from pathlib import Path
import subprocess
import tempfile


def main():
	parser = argparse.ArgumentParser(description=__doc__)
	parser.add_argument('--fxc', required=True)
	parser.add_argument('--glslang', default='glslangValidator')
	parser.add_argument('--wsl', action='store_true')
	parser.add_argument('--check', action='store_true', help='Verify checked-in bytes without rewriting them')
	args = parser.parse_args()
	module = Path(__file__).resolve().parents[2]
	source = module / 'Resources' / 'Assets' / 'Shaders'
	arrays = []
	# Use a source-adjacent temporary directory so WSL can access the compiler outputs.
	with tempfile.TemporaryDirectory(prefix='.shader-', dir=source) as work:
		for stage, profile in [('vert', 'vs_5_1'), ('frag', 'ps_5_1')]:
			output = Path(work) / (stage + '.dxbc')
			subprocess.run([args.fxc, '/nologo', '/O3', '/T', profile, '/E', 'main', '/Fo', str(output), str(source / f'Draw2D.{stage}.hlsl')], check=True)
			arrays.append((stage.title() + 'Dxbc', output.read_bytes()))
			d3d11_source = Path(work) / (stage + '.d3d11.hlsl')
			d3d11_source.write_text(re.sub(r',\s*space\d+', '', (source / f'Draw2D.{stage}.hlsl').read_text(encoding='utf-8')), encoding='utf-8')
			output = Path(work) / (stage + '.d3d11.dxbc')
			subprocess.run([args.fxc, '/nologo', '/O3', '/T', profile.replace('5_1', '5_0'), '/E', 'main', '/Fo', str(output), str(d3d11_source)], check=True)
			arrays.append((stage.title() + 'D3d11', output.read_bytes()))
			output = Path(work) / (stage + '.spv')
			path = lambda p: subprocess.check_output(['wsl', '--exec', 'wslpath', '-a', str(p)], text=True).strip() if args.wsl else str(p)
			command = ['wsl', '--exec'] if args.wsl else []
			subprocess.run(command + [args.glslang, '-V', '--target-env', 'vulkan1.0', '-o', path(output), path(source / f'Draw2D.{stage}')], check=True)
			arrays.append((stage.title() + 'Spirv', output.read_bytes()))
	text = '// SPDX-FileCopyrightText: VanstySanic\n// SPDX-License-Identifier: MIT\n\n// Generated by Resources/Tools/generate-shaders.py.\n'
	for name, data in arrays:
		text += f'alignas(4) static constexpr unsigned char {name}[] = {{\n'
		text += '\n'.join('\t' + ', '.join(f'0x{v:02x}' for v in data[i:i+16]) + ',' for i in range(0, len(data), 16)) + '\n};\n'
	text += 'static constexpr char MetalSource[] = R"msl(' + (source / 'Draw2D.metal').read_text(encoding='utf-8') + ')msl";\n'
	for name, filename in [('OpenGlVertex', 'Draw2D.gl.vert'), ('OpenGlFragment', 'Draw2D.gl.frag')]:
		text += f'static constexpr char {name}[] = R"glsl(' + (source / filename).read_text(encoding='utf-8') + ')glsl";\n'
	text += 'static constexpr char WebGpuSource[] = R"wgsl(' + (source / 'Draw2D.wgsl').read_text(encoding='utf-8') + ')wgsl";\n'
	destination = module / 'Private' / 'VeroScriptSdl3Shaders.inl'
	expected = text.replace('\n', '\r\n').encode('utf-8')
	if args.check:
		if not destination.exists() or destination.read_bytes() != expected:
			raise SystemExit('Embedded shaders differ from compiled sources; regenerate without --check.')
		print('Embedded shaders match compiled sources.')
	else:
		destination.write_bytes(expected)


if __name__ == '__main__':
	main()
