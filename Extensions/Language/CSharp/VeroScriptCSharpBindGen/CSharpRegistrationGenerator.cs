using System.Text.RegularExpressions;
using VeroScript.CSharpFrontend;

namespace VeroScript.CSharpBindGen;

internal static class CSharpRegistrationGenerator
{
	private static readonly Regex IdentifierPattern = new(
		@"^@?[_\p{L}][\p{L}\p{Nd}\p{Mn}\p{Mc}\p{Pc}\p{Cf}]*$", RegexOptions.Compiled);
	private static readonly HashSet<string> ReservedKeywords = new(
		"abstract as base bool break byte case catch char checked class const continue decimal default delegate do double else enum event explicit extern false finally fixed float for foreach goto if implicit in int interface internal is lock long namespace new null object operator out override params private protected public readonly ref return sbyte sealed short sizeof stackalloc static string struct switch this throw true try typeof uint ulong unchecked unsafe ushort using virtual void volatile while"
			.Split(' '), StringComparer.Ordinal);

	internal static string Generate(IReadOnlyList<CSharpTypeDeclaration> sourceTypes,
		CSharpTypeMapOptions mapOptions, CSharpBindGenOptions options,
		List<CSharpDiagnostic> diagnostics)
	{
		if (!IsQualifiedIdentifier(options.RegistrationNamespace)
			|| !IsIdentifier(options.RegistrationClassName))
		{
			diagnostics.Add(new(CSharpDiagnosticSeverity.Error, "VSCB3000",
				"Generated registration namespace and class name must be valid C# identifiers.",
				CSharpSourceLocation.None));
			return "";
		}
		CSharpTypeDeclaration[] types = sourceTypes.Where(type =>
			type.Kind is CSharpTypeKind.Class or CSharpTypeKind.Struct or CSharpTypeKind.Enum
			&& type.TypeParameters.Count == 0).ToArray();
		var typeIds = types.Select((type, index) => (type.QualifiedName, Name: $"__typeId{index}"))
			.ToDictionary(pair => pair.QualifiedName, pair => pair.Name, StringComparer.Ordinal);
		var text = new StringBuilder();
		text.AppendLine("// SPDX-FileCopyrightText: VanstySanic").AppendLine("// SPDX-License-Identifier: MIT").AppendLine().AppendLine("// <auto-generated/>")
			.AppendLine("#nullable enable")
			.Append("namespace ").Append(options.RegistrationNamespace).AppendLine(";")
			.AppendLine()
			.Append("public static class ").Append(options.RegistrationClassName).AppendLine()
			.AppendLine("{")
			.AppendLine("\tpublic static void Register(global::VeroScript.VeroScriptSession session)")
			.AppendLine("\t{")
			.AppendLine("\t\tglobal::System.ArgumentNullException.ThrowIfNull(session);");
		for (int i = 0; i < types.Length; ++i)
		{
			CSharpTypeDeclaration type = types[i];
			text.Append("\t\tuint __typeId").Append(i)
				.AppendLine(" = session.RegisterHostType(new global::VeroScript.VeroScriptHostTypeDefinition")
				.AppendLine("\t\t{")
				.Append("\t\t\tName = ").Append(Literal(ScriptName(type.QualifiedName))).AppendLine(",")
				.Append("\t\t\tKind = global::VeroScript.VeroScriptHostTypeKind.")
				.Append(type.Kind switch
				{
					CSharpTypeKind.Enum => "Enum",
					CSharpTypeKind.Struct => "Struct",
					_ => "Class"
				})
				.AppendLine(",")
				.Append("\t\t\tDocumentation = ")
				.Append(Literal(CSharpDocumentation.Parse(type.DocumentationXml).Summary)).AppendLine(",")
				.AppendLine("\t\t\tInheritable = false,")
				.Append("\t\t\tScopedEnum = ").Append(type.Kind == CSharpTypeKind.Enum ? "true" : "false").AppendLine(",")
				.Append("\t\t\tEnumUnderlyingTypeName = ")
				.Append(Literal(type.EnumUnderlyingType is null ? "" : MapVero(type.EnumUnderlyingType, mapOptions, diagnostics))).AppendLine()
				.AppendLine("\t\t});");
		}
		for (int i = 0; i < types.Length; ++i)
		{
			AppendMembers(text, types[i], $"__typeId{i}", typeIds, mapOptions, options, diagnostics);
		}

		text.AppendLine("\t}");
		if (types.Any(TypeUsesGeneratedContainerMarshalling))
		{
			AppendContainerHelpers(text);
		}

		text.AppendLine("}");
		return text.ToString();
	}

	private static void AppendMembers(StringBuilder text, CSharpTypeDeclaration owner, string ownerId,
		IReadOnlyDictionary<string, string> typeIds, CSharpTypeMapOptions mapOptions,
		CSharpBindGenOptions options,
		List<CSharpDiagnostic> diagnostics)
	{
		if (owner.Kind == CSharpTypeKind.Enum)
		{
			foreach (CSharpEnumValueDeclaration value in owner.EnumValues)
			{
				text.Append("\t\tsession.RegisterHostMember(").Append(ownerId)
					.AppendLine(", new global::VeroScript.VeroScriptHostMemberDefinition")
					.AppendLine("\t\t{")
					.AppendLine("\t\t\tKind = global::VeroScript.VeroScriptHostMemberKind.EnumMember,")
					.Append("\t\t\tName = ").Append(Literal(value.Name)).AppendLine(",")
					.Append("\t\t\tReturnType = ").Append(TypeExpression(
						new("", owner.QualifiedName, CSharpTypeKind.Enum, false, 0, CSharpRefKind.None, [], value.Location),
						mapOptions, diagnostics)).AppendLine(",")
					.Append("\t\t\tEnumValue = ").Append(value.ConstantValue).AppendLine("L")
					.AppendLine("\t\t});");
			}
			return;
		}
		if (owner.Kind == CSharpTypeKind.Struct
			&& (owner.Fields.Any(field => field.Accessibility == CSharpAccessibility.Public && !field.IsStatic)
				|| owner.Properties.Any(property => property.Accessibility == CSharpAccessibility.Public && !property.IsStatic)
				|| owner.Callables.Any(callable => callable.Accessibility == CSharpAccessibility.Public && !callable.IsStatic
					&& callable.Kind != CSharpCallableKind.Constructor)))
		{
			diagnostics.Add(new(CSharpDiagnosticSeverity.Error, "VSCB3001",
				$"Live registration for mutable value-type host '{owner.QualifiedName}' requires an explicit boxing/write-back policy.",
				owner.Declarations.Count == 0 ? CSharpSourceLocation.None : owner.Declarations[0]));
			return;
		}
		foreach (CSharpFieldDeclaration field in owner.Fields.Where(field =>
			field.Accessibility == CSharpAccessibility.Public
			&& !HasAttribute(field.Attributes, options.IgnoreAttributeName)))
		{
			if (field.Type.RefKind != CSharpRefKind.None)
			{
				continue;
			}

			if (field.IsStatic && UsesContainer(field.Type))
			{
				AddStaticContainerDiagnostic(field.QualifiedName, field.Location, diagnostics);
				continue;
			}
			if (!CanMarshal(field.Type, mapOptions, diagnostics, field.Location))
			{
				continue;
			}

			if (field.IsStatic)
			{
				AppendMember(text, owner, ownerId, field.Name, field.DocumentationXml,
								"StaticConstant", field.Type, [],
								WriteValue("returnValue", field.Type, $"{Target(owner)}.{Identifier(field.Name)}", typeIds),
								mapOptions, diagnostics, typeIds);
			}
			else
			{
				AppendMember(text, owner, ownerId, field.Name, field.DocumentationXml,
					"Field", field.Type, [],
					WriteValue("returnValue", field.Type, $"__instance.{Identifier(field.Name)}", typeIds),
					mapOptions, diagnostics, typeIds, needsInstance: true);
				if (!field.IsReadOnly && !field.IsConst)
				{
					AppendMember(text, owner, ownerId, field.Name, field.DocumentationXml, "PropertySetter",
										VoidType(field.Location), [new("value", field.Type, false, "", false, [], field.Location)],
										$"__instance.{Identifier(field.Name)} = __arg0;", mapOptions, diagnostics,
										typeIds, needsInstance: true);
				}
			}
		}
		foreach (CSharpPropertyDeclaration property in owner.Properties.Where(property =>
			property.Accessibility == CSharpAccessibility.Public
			&& !HasAttribute(property.Attributes, options.IgnoreAttributeName)))
		{
			if (property.Type.RefKind != CSharpRefKind.None)
			{
				continue;
			}

			if (property.IsStatic && (UsesContainer(property.Type)
							|| property.Parameters.Any(parameter => UsesContainer(parameter.Type))))
			{
				AddStaticContainerDiagnostic(property.QualifiedName, property.Location, diagnostics);
				continue;
			}
			if (!CanMarshal(property.Type, mapOptions, diagnostics, property.Location)
				|| property.Parameters.Any(parameter => !CanMarshal(parameter.Type, mapOptions, diagnostics, parameter.Location)))
			{
				continue;
			}

			if (property.IsStatic)
			{
				if (property.HasGetter
					&& (!property.HasSetter || property.SetterAccessibility != CSharpAccessibility.Public)
					&& property.GetterAccessibility == CSharpAccessibility.Public)
				{
					AppendMember(text, owner, ownerId, property.Name, property.DocumentationXml,
										"StaticConstant", property.Type, [],
										WriteValue("returnValue", property.Type,
											$"{Target(owner)}.{Identifier(property.Name)}", typeIds),
										mapOptions, diagnostics, typeIds);
				}
				else
				{
					diagnostics.Add(new(CSharpDiagnosticSeverity.Error, "VSCB1007",
										$"Static property '{property.QualifiedName}' has no faithful Binding Catalog v1 member kind.",
										property.Location));
				}

				continue;
			}
			string access = property.IsIndexer
				? "__instance[" + string.Join(", ", Enumerable.Range(0, property.Parameters.Count).Select(index => $"__arg{index}")) + "]"
				: $"__instance.{Identifier(property.Name)}";
			if (property.HasGetter && property.GetterAccessibility == CSharpAccessibility.Public)
			{
				AppendMember(text, owner, ownerId, property.Name, property.DocumentationXml,
								"PropertyGetter", property.Type,
								property.Parameters, WriteValue("returnValue", property.Type, access, typeIds),
								mapOptions, diagnostics, typeIds, needsInstance: true);
			}

			if (property.HasSetter && !property.IsInitOnly
							&& property.SetterAccessibility == CSharpAccessibility.Public)
			{
				CSharpParameterDeclaration[] parameters = property.Parameters
					.Append(new("value", property.Type, false, "", false, [], property.Location)).ToArray();
				AppendMember(text, owner, ownerId, property.Name, property.DocumentationXml, "PropertySetter",
					VoidType(property.Location), parameters, $"{access} = __arg{parameters.Length - 1};",
					mapOptions, diagnostics, typeIds, needsInstance: true);
			}
		}
		foreach (CSharpCallableDeclaration callable in owner.Callables.Where(callable =>
			callable.Accessibility == CSharpAccessibility.Public
			&& callable.Kind is CSharpCallableKind.Method or CSharpCallableKind.Constructor
			&& !(owner.IsAbstract && callable.Kind == CSharpCallableKind.Constructor)
			&& !HasAttribute(callable.Attributes, options.IgnoreAttributeName)))
		{
			if (callable.ReturnType.RefKind != CSharpRefKind.None)
			{
				continue;
			}

			if (callable.IsStatic && (UsesContainer(callable.ReturnType)
							|| callable.Parameters.Any(parameter => UsesContainer(parameter.Type))))
			{
				AddStaticContainerDiagnostic(callable.QualifiedName, callable.Location, diagnostics);
				continue;
			}
			if (!CanMarshal(callable.ReturnType, mapOptions, diagnostics, callable.Location)
				|| callable.Parameters.Any(parameter => !CanMarshal(parameter.Type, mapOptions, diagnostics, parameter.Location)))
			{
				continue;
			}

			string arguments = string.Join(", ", callable.Parameters.Select((parameter, index) =>
							parameter.Type.RefKind switch
							{
								CSharpRefKind.Ref => $"ref __arg{index}",
								CSharpRefKind.Out => $"out __arg{index}",
								CSharpRefKind.In or CSharpRefKind.RefReadOnly => $"in __arg{index}",
								_ => $"__arg{index}"
							}));
			string invocation;
			bool needsInstance;
			if (callable.Kind == CSharpCallableKind.Constructor)
			{
				invocation = $"returnValue.SetHostObject({ownerId}, {Literal(ScriptName(owner.QualifiedName))}, new {Target(owner)}({arguments}));";
				needsInstance = false;
			}
			else
			{
				string call = callable.IsStatic ? $"{Target(owner)}.{Identifier(callable.Name)}({arguments})"
					: $"__instance.{Identifier(callable.Name)}({arguments})";
				invocation = IsVoid(callable.ReturnType) ? call + ";"
					: WriteValue("returnValue", callable.ReturnType, call, typeIds);
				needsInstance = !callable.IsStatic;
			}
			AppendMember(text, owner, ownerId,
				callable.Kind == CSharpCallableKind.Constructor ? owner.Name : callable.Name,
				callable.DocumentationXml,
				callable.Kind == CSharpCallableKind.Constructor ? "Constructor" : callable.IsStatic ? "StaticMethod" : "Method",
				callable.Kind == CSharpCallableKind.Constructor
					? HostType(owner, callable.Location) : callable.ReturnType,
				callable.Parameters, invocation, mapOptions, diagnostics, typeIds, needsInstance);
		}
	}

	private static void AppendMember(StringBuilder text, CSharpTypeDeclaration owner, string ownerId,
		string name, string documentationXml, string kind, CSharpTypeReference returnType,
		IReadOnlyList<CSharpParameterDeclaration> parameters, string invocation,
		CSharpTypeMapOptions mapOptions, List<CSharpDiagnostic> diagnostics,
		IReadOnlyDictionary<string, string> typeIds,
		bool needsInstance = false)
	{
		CSharpDocumentation documentation = CSharpDocumentation.Parse(documentationXml);
		text.Append("\t\tsession.RegisterHostMember(").Append(ownerId)
			.AppendLine(", new global::VeroScript.VeroScriptHostMemberDefinition")
			.AppendLine("\t\t{")
			.Append("\t\t\tKind = global::VeroScript.VeroScriptHostMemberKind.").Append(kind).AppendLine(",")
			.Append("\t\t\tName = ").Append(Literal(name)).AppendLine(",")
			.Append("\t\t\tReturnType = ").Append(TypeExpression(returnType, mapOptions, diagnostics)).AppendLine(",")
			.Append("\t\t\tParameters = ").Append(ParameterExpressions(parameters, mapOptions, diagnostics)).AppendLine(",")
			.Append("\t\t\tParameterNames = [")
			.Append(string.Join(", ", parameters.Select(parameter => Literal(parameter.Name)))).AppendLine("],")
			.Append("\t\t\tDocumentation = ").Append(Literal(documentation.Summary)).AppendLine(",")
			.Append("\t\t\tParameterDocumentation = [")
			.Append(string.Join(", ", parameters.Select(parameter =>
				Literal(documentation.Parameters.GetValueOrDefault(parameter.Name, ""))))).AppendLine("],")
			.Append("\t\t\tReturnDocumentation = ").Append(Literal(documentation.Returns)).AppendLine(",")
			.AppendLine("\t\t\tCallback = (context, returnValue) =>")
			.AppendLine("\t\t\t{")
			.AppendLine("\t\t\t\ttry")
			.AppendLine("\t\t\t\t{");
		if (needsInstance)
		{
			text.Append("\t\t\t\t\t").Append(Target(owner)).Append(" __instance = context.GetHostThis<")
						.Append(Target(owner)).AppendLine(">() ?? throw new global::System.InvalidOperationException(\"Managed host receiver is unavailable.\");");
		}

		int argumentOffset = needsInstance ? 1 : 0;
		for (int i = 0; i < parameters.Count; ++i)
		{
			CSharpParameterDeclaration parameter = parameters[i];
			text.Append("\t\t\t\t\t").Append(SourceType(parameter.Type)).Append(" __arg").Append(i).Append(" = ");
			if (parameter.Type.RefKind == CSharpRefKind.Out)
			{
				text.AppendLine("default!;");
			}
			else
			{
				text.Append(ReadValue(parameter.Type, i + argumentOffset)).AppendLine(";");
			}
		}
		text.Append("\t\t\t\t\t").AppendLine(invocation);
		for (int i = 0; i < parameters.Count; ++i)
		{
			if (parameters[i].Type.RefKind is CSharpRefKind.Ref or CSharpRefKind.Out)
			{
				text.Append("\t\t\t\t\t").AppendLine(WriteValue(
								$"context.GetMutableArgument({i + argumentOffset})", parameters[i].Type,
								$"__arg{i}", typeIds));
			}
		}

		text.AppendLine("\t\t\t\t}")
						.AppendLine("\t\t\t\tcatch (global::System.Exception exception)")
						.AppendLine("\t\t\t\t{")
						.Append("\t\t\t\t\tcontext.SetError(").Append(Literal($"C# binding '{owner.QualifiedName}.{name}' failed: "))
						.AppendLine(" + exception.Message);")
						.AppendLine("\t\t\t\t}")
						.AppendLine("\t\t\t}")
						.AppendLine("\t\t});");
	}

	private static bool CanMarshal(CSharpTypeReference type, CSharpTypeMapOptions options,
		List<CSharpDiagnostic> diagnostics, CSharpSourceLocation location)
	{
		CSharpTypeMapResult result = CSharpTypeMapper.MapTypeToVeroScript(type, options);
		if (!result.Success)
		{
			diagnostics.Add(new(CSharpDiagnosticSeverity.Error, result.ErrorCode, result.ErrorMessage, location));
			return false;
		}
		if ((type.Kind == CSharpTypeKind.Array || type.TypeArguments.Count != 0)
			&& !IsSupportedContainer(type))
		{
			diagnostics.Add(new(CSharpDiagnosticSeverity.Error, "VSCB3002",
				$"Live generated marshalling for container type '{type.DisplayName}' is only supported for one-level scalar or string elements.", location));
			return false;
		}
		return true;
	}

	private static string TypeExpression(CSharpTypeReference type, CSharpTypeMapOptions options,
		List<CSharpDiagnostic> diagnostics)
	{
		if (TryContainerKind(type, out string? kind))
		{
			return $"new(global::VeroScript.VeroScriptNativeTypeKind.{kind}, null, "
						+ string.Join(", ", type.TypeArguments.Select(argument =>
							TypeExpression(argument, options, diagnostics))) + ")";
		}

		string vero = MapVero(type, options, diagnostics);
		return vero switch
		{
			"void" => "global::VeroScript.VeroScriptNativeType.Void",
			"int8" => "global::VeroScript.VeroScriptNativeType.Int8",
			"uint8" => "global::VeroScript.VeroScriptNativeType.UInt8",
			"int16" => "global::VeroScript.VeroScriptNativeType.Int16",
			"uint16" => "global::VeroScript.VeroScriptNativeType.UInt16",
			"int" => "global::VeroScript.VeroScriptNativeType.Int32",
			"unsigned int" => "global::VeroScript.VeroScriptNativeType.UInt32",
			"int64" => "global::VeroScript.VeroScriptNativeType.Int64",
			"uint64" => "global::VeroScript.VeroScriptNativeType.UInt64",
			"float" => "global::VeroScript.VeroScriptNativeType.Float",
			"double" => "global::VeroScript.VeroScriptNativeType.Double",
			"bool" => "global::VeroScript.VeroScriptNativeType.Bool",
			"string" => "global::VeroScript.VeroScriptNativeType.String",
			_ when type.Kind == CSharpTypeKind.Enum =>
				$"new(global::VeroScript.VeroScriptNativeTypeKind.Enum, {Literal(ScriptName(type.QualifiedName))})",
			_ => $"new(global::VeroScript.VeroScriptNativeTypeKind.HostObject, {Literal(ScriptName(type.QualifiedName))})"
		};
	}

	private static string ParameterExpressions(IReadOnlyList<CSharpParameterDeclaration> parameters,
		CSharpTypeMapOptions options, List<CSharpDiagnostic> diagnostics)
		=> "[" + string.Join(", ", parameters.Select(parameter =>
			$"new global::VeroScript.VeroScriptNativeParameter({TypeExpression(parameter.Type, options, diagnostics)}, "
			+ "global::VeroScript.VeroScriptParameterFlags."
			+ (parameter.Type.RefKind switch
			{
				CSharpRefKind.Ref or CSharpRefKind.Out => "Ref",
				CSharpRefKind.In or CSharpRefKind.RefReadOnly => "Ref | global::VeroScript.VeroScriptParameterFlags.ConstRef",
				_ => "None"
			}) + ")")) + "]";

	private static string ReadValue(CSharpTypeReference type, int index)
	{
		string source = $"context.GetArgument({index})";
		if (TryContainerKind(type, out string? kind))
		{
			if (kind is "Array" or "Queue" or "Stack" && type.TypeArguments.Count == 1)
			{
				CSharpTypeReference element = type.TypeArguments[0];
				string values = $"__ReadSequence<{SourceType(element)}>({source}, {Reader(element)})";
				if (type.Kind == CSharpTypeKind.Array)
				{
					return $"global::System.Linq.Enumerable.ToArray({values})";
				}

				if (kind == "Queue") return $"new global::System.Collections.Generic.Queue<{SourceType(element)}>({values})";
				if (kind == "Stack") return $"new global::System.Collections.Generic.Stack<{SourceType(element)}>({values})";
				return values;
			}
			if (kind is "Map" or "OrderedMap" && type.TypeArguments.Count == 2)
			{
				CSharpTypeReference key = type.TypeArguments[0];
				CSharpTypeReference value = type.TypeArguments[1];
				string helper = kind == "OrderedMap" ? "__ReadSortedMap" : "__ReadMap";
				return $"{helper}<{SourceType(key)}, {SourceType(value)}>({source}, {Reader(key)}, {Reader(value)})";
			}
			if (kind == "Set" && type.TypeArguments.Count == 1)
			{
				CSharpTypeReference element = type.TypeArguments[0];
				return $"__ReadSet<{SourceType(element)}>({source}, {Reader(element)})";
			}
		}
		return type.DisplayName switch
		{
			"sbyte" => $"context.GetArgument({index}).GetInt8()",
			"byte" => $"context.GetArgument({index}).GetUInt8()",
			"short" => $"context.GetArgument({index}).GetInt16()",
			"ushort" => $"context.GetArgument({index}).GetUInt16()",
			"char" => $"(char)context.GetArgument({index}).GetUInt16()",
			"int" => $"context.GetArgument({index}).GetInt32()",
			"uint" => $"context.GetArgument({index}).GetUInt32()",
			"long" => $"context.GetArgument({index}).GetInt64()",
			"ulong" => $"context.GetArgument({index}).GetUInt64()",
			"float" => $"context.GetArgument({index}).GetFloat()",
			"double" => $"context.GetArgument({index}).GetDouble()",
			"bool" => $"context.GetArgument({index}).GetBool()",
			"string" => $"context.GetArgument({index}).GetString()",
			_ when type.Kind == CSharpTypeKind.Enum =>
				$"({SourceType(type)})context.GetArgument({index}).GetEnum().Value",
			_ => $"context.GetArgument({index}).GetHostObject<{SourceType(type)}>()"
		};
	}

	private static string WriteValue(string target, CSharpTypeReference type, string value,
		IReadOnlyDictionary<string, string> typeIds)
	{
		if (TryContainerKind(type, out string? kind))
		{
			if (kind is "Array" or "Queue" or "Stack" && type.TypeArguments.Count == 1)
			{
				CSharpTypeReference element = type.TypeArguments[0];
				return $"__WriteSequence({target}, global::VeroScript.VeroScriptValueKind.{kind}, "
					+ $"{Literal(VeroType(element))}, {value}, {Writer(element)});";
			}
			if (kind is "Map" or "OrderedMap" && type.TypeArguments.Count == 2)
			{
				CSharpTypeReference key = type.TypeArguments[0];
				CSharpTypeReference item = type.TypeArguments[1];
				return $"__WriteMap({target}, {Literal(VeroType(key))}, {Literal(VeroType(item))}, "
					+ $"{value}, {Writer(key)}, {Writer(item)}, {(kind == "OrderedMap" ? "true" : "false")});";
			}
			if (kind == "Set" && type.TypeArguments.Count == 1)
			{
				CSharpTypeReference element = type.TypeArguments[0];
				return $"__WriteSet({target}, {Literal(VeroType(element))}, {value}, {Writer(element)});";
			}
		}
		return type.DisplayName switch
		{
			"string" => $"{target}.SetString({value});",
			_ when type.Kind == CSharpTypeKind.Enum =>
				$"{target}.SetEnum({Literal(ScriptName(type.QualifiedName))}, (long)({value}));",
			_ when typeIds.ContainsKey(type.QualifiedName) =>
				$"{target}.SetHostObject({typeIds[type.QualifiedName]}, {Literal(ScriptName(type.QualifiedName))}, {value});",
			_ => $"{target}.Set({value});"
		};
	}

	private static string MapVero(CSharpTypeReference type, CSharpTypeMapOptions options,
		List<CSharpDiagnostic> diagnostics)
	{
		CSharpTypeMapResult result = CSharpTypeMapper.MapTypeToVeroScript(type, options);
		if (result.Success) return result.VeroType;
		diagnostics.Add(new(CSharpDiagnosticSeverity.Error, result.ErrorCode, result.ErrorMessage, type.Location));
		return "void";
	}

	private static CSharpTypeReference VoidType(CSharpSourceLocation location)
		=> new("void", "void", CSharpTypeKind.Struct, false, 0, CSharpRefKind.None, [], location);
	private static CSharpTypeReference HostType(CSharpTypeDeclaration owner, CSharpSourceLocation location)
		=> new(owner.Name, owner.QualifiedName, owner.Kind, false, 0, CSharpRefKind.None, [], location);
	private static bool IsVoid(CSharpTypeReference type) => type.DisplayName == "void";
	private static string SourceType(CSharpTypeReference type)
	{
		if (type.Kind == CSharpTypeKind.Array && type.TypeArguments.Count == 1)
		{
			return SourceType(type.TypeArguments[0]) + "[]";
		}

		return type.DisplayName switch
		{
			"sbyte" or "byte" or "short" or "ushort" or "int" or "uint" or "long" or "ulong"
				or "float" or "double" or "bool" or "char" or "string" => type.DisplayName,
			_ => "global::" + type.QualifiedName
		};
	}
	private static string Target(CSharpTypeDeclaration type) => "global::" + type.QualifiedName;

	private static bool IsSupportedContainer(CSharpTypeReference type)
		=> TryContainerKind(type, out string? kind) && kind != "OrderedMap"
			&& type.TypeArguments.Count is 1 or 2
			&& type.TypeArguments.All(IsScalarOrString);

	private static bool TypeUsesGeneratedContainerMarshalling(CSharpTypeDeclaration type)
		=> type.Fields.Any(field => !field.IsStatic && IsSupportedContainer(field.Type))
			|| type.Properties.Any(property => !property.IsStatic
				&& (IsSupportedContainer(property.Type)
					|| property.Parameters.Any(parameter => IsSupportedContainer(parameter.Type))))
			|| type.Callables.Any(callable => !callable.IsStatic
				&& (IsSupportedContainer(callable.ReturnType)
					|| callable.Parameters.Any(parameter => IsSupportedContainer(parameter.Type))));

	private static bool UsesContainer(CSharpTypeReference type)
		=> type.Kind == CSharpTypeKind.Array || TryContainerKind(type, out _);

	private static void AddStaticContainerDiagnostic(string member,
		CSharpSourceLocation location, List<CSharpDiagnostic> diagnostics)
		=> diagnostics.Add(new(CSharpDiagnosticSeverity.Error, "VSCB3004",
			$"Live generated registration for static container member '{member}' is not supported by the current runtime member type inference; use an instance member or generate only the AOT bridge.",
			location));

	private static bool IsScalarOrString(CSharpTypeReference type)
		=> type.Kind == CSharpTypeKind.Enum || type.DisplayName is "sbyte" or "byte" or "short"
			or "ushort" or "char" or "int" or "uint" or "long" or "ulong" or "float"
			or "double" or "bool" or "string";

	private static bool TryContainerKind(CSharpTypeReference type, out string? kind)
	{
		if (type.Kind == CSharpTypeKind.Array)
		{
			kind = "Array";
			return type.ArrayRank == 1 && type.TypeArguments.Count == 1;
		}
		int open = type.QualifiedName.IndexOf('<', StringComparison.Ordinal);
		string name = open < 0 ? type.QualifiedName : type.QualifiedName[..open];
		kind = name switch
		{
			"System.Collections.Generic.List" => "Array",
			"System.Collections.Generic.Dictionary" => "Map",
			"System.Collections.Generic.SortedDictionary" => "OrderedMap",
			"System.Collections.Generic.HashSet" => "Set",
			"System.Collections.Generic.Queue" => "Queue",
			"System.Collections.Generic.Stack" => "Stack",
			_ => null
		};
		return kind is not null;
	}

	private static string VeroType(CSharpTypeReference type) => type.DisplayName switch
	{
		"sbyte" => "int8",
		"byte" => "uint8",
		"short" => "int16",
		"ushort" or "char" => "uint16",
		"int" => "int",
		"uint" => "unsigned int",
		"long" => "int64",
		"ulong" => "uint64",
		"float" => "float",
		"double" => "double",
		"bool" => "bool",
		"string" => "string",
		_ when type.Kind == CSharpTypeKind.Enum => ScriptName(type.QualifiedName),
		_ => ScriptName(type.QualifiedName)
	};

	private static string Reader(CSharpTypeReference type) => type.DisplayName switch
	{
		"sbyte" => "static __value => __value.GetInt8()",
		"byte" => "static __value => __value.GetUInt8()",
		"short" => "static __value => __value.GetInt16()",
		"ushort" => "static __value => __value.GetUInt16()",
		"char" => "static __value => (char)__value.GetUInt16()",
		"int" => "static __value => __value.GetInt32()",
		"uint" => "static __value => __value.GetUInt32()",
		"long" => "static __value => __value.GetInt64()",
		"ulong" => "static __value => __value.GetUInt64()",
		"float" => "static __value => __value.GetFloat()",
		"double" => "static __value => __value.GetDouble()",
		"bool" => "static __value => __value.GetBool()",
