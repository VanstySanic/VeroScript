	private static string Writer(CSharpTypeReference type) => type.DisplayName switch
	{
		"string" => "static (__target, __value) => __target.SetString(__value)",
		"char" => "static (__target, __value) => __target.Set((ushort)__value)",
		_ when type.Kind == CSharpTypeKind.Enum =>
			$"static (__target, __value) => __target.SetEnum({Literal(ScriptName(type.QualifiedName))}, (long)__value)",
		_ => "static (__target, __value) => __target.Set(__value)"
	};

