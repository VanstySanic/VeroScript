	private static string ScriptName(string name) => name.Replace(".", "::", StringComparison.Ordinal);
	private static string Literal(string value) => JsonSerializer.Serialize(value);
	private static string Identifier(string value) => "@" + value;
	private static bool HasAttribute(IReadOnlyList<CSharpAttribute> attributes, string name)
		=> attributes.Any(attribute => attribute.TypeName == name
			|| attribute.TypeName.EndsWith("." + name, StringComparison.Ordinal));
	private static bool IsQualifiedIdentifier(string value)
		=> !string.IsNullOrWhiteSpace(value)
			&& value.Split('.').All(IsIdentifier);
	private static bool IsIdentifier(string value)
		=> IdentifierPattern.IsMatch(value)
			&& (value[0] == '@' || !ReservedKeywords.Contains(value));
