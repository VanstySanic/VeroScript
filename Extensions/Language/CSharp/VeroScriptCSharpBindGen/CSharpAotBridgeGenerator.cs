using System.Text;
using VeroScript.CSharpFrontend;

namespace VeroScript.CSharpBindGen;
/// <summary>
/// Emits implementations for the partial host-call contracts produced by
/// VeroScriptCSharpAot. The bridge is compiled into the generated AOT assembly
/// together with a reference to the user's managed declarations.
/// </summary>
internal static class CSharpAotBridgeGenerator
{
	internal static string Generate(IReadOnlyList<CSharpTypeDeclaration> sourceTypes, CSharpBindGenOptions options, List<CSharpDiagnostic> diagnostics)
	{
		CSharpTypeDeclaration[] types = sourceTypes.Where(type => type.IsEffectivelyPublic && !HasAttribute(type.Attributes, options.IgnoreAttributeName) && (!options.RequireBindingAttribute || HasAttribute(type.Attributes, options.BindingAttributeName)) && type.TypeParameters.Count == 0 && type.Kind is CSharpTypeKind.Class or CSharpTypeKind.Struct or CSharpTypeKind.Enum).ToArray();
		var enumUnderlyingTypes = types.Where(type => type.Kind == CSharpTypeKind.Enum).ToDictionary(type => type.QualifiedName, type => type.EnumUnderlyingType?.DisplayName ?? "int", StringComparer.Ordinal);
		foreach (CSharpTypeDeclaration type in types.Where(type => type.Kind != CSharpTypeKind.Enum))
		{
			foreach (CSharpFieldDeclaration field in type.Fields.Where(field => field.Accessibility == CSharpAccessibility.Public && !HasAttribute(field.Attributes, options.IgnoreAttributeName)))
			{
				if (type.Kind == CSharpTypeKind.Struct && !field.IsStatic && !field.IsConst && !field.IsReadOnly)
				{
					AddStructWriteBackDiagnostic(field.QualifiedName, field.Location, diagnostics);
				}

				ValidateAotType(field.Type, field.QualifiedName, field.Location, diagnostics);
			}

			foreach (CSharpPropertyDeclaration property in type.Properties.Where(property => property.Accessibility == CSharpAccessibility.Public && !HasAttribute(property.Attributes, options.IgnoreAttributeName)))
			{
				if (type.Kind == CSharpTypeKind.Struct && !property.IsStatic && property.HasSetter && !property.IsInitOnly && property.SetterAccessibility == CSharpAccessibility.Public)
				{
					AddStructWriteBackDiagnostic(property.QualifiedName, property.Location, diagnostics);
				}

				ValidateAotType(property.Type, property.QualifiedName, property.Location, diagnostics);
				foreach (CSharpParameterDeclaration parameter in property.Parameters)
				{
					ValidateAotType(parameter.Type, property.QualifiedName, parameter.Location, diagnostics);
				}
			}

			foreach (CSharpCallableDeclaration callable in type.Callables.Where(callable => callable.Accessibility == CSharpAccessibility.Public && callable.Kind is CSharpCallableKind.Method or CSharpCallableKind.Constructor && !(type.IsAbstract && callable.Kind == CSharpCallableKind.Constructor) && !HasAttribute(callable.Attributes, options.IgnoreAttributeName)))
			{
				if (type.Kind == CSharpTypeKind.Struct && callable.Kind == CSharpCallableKind.Method && !callable.IsStatic)
				{
					AddStructWriteBackDiagnostic(callable.QualifiedName, callable.Location, diagnostics);
				}

				if (callable.Kind != CSharpCallableKind.Constructor)
				{
					ValidateAotType(callable.ReturnType, callable.QualifiedName, callable.Location, diagnostics);
				}

				foreach (CSharpParameterDeclaration parameter in callable.Parameters)
				{
					ValidateAotType(parameter.Type, callable.QualifiedName, parameter.Location, diagnostics);
				}
			}
		}

		if (diagnostics.Any(diagnostic => diagnostic.Severity == CSharpDiagnosticSeverity.Error))
		{
			return "";
		}

		var text = new StringBuilder();
		text.AppendLine("// SPDX-FileCopyrightText: VanstySanic").AppendLine("// SPDX-License-Identifier: MIT").AppendLine().AppendLine("// <auto-generated/>").AppendLine("// Managed implementations for VeroScriptCSharpAot host-call contracts.").AppendLine("#nullable enable").AppendLine().AppendLine("internal static partial class VeroScriptGeneratedProgram").AppendLine("{");
		foreach (CSharpTypeDeclaration owner in types)
		{
			if (owner.Kind == CSharpTypeKind.Enum)
			{
				continue;
			}

			foreach (CSharpFieldDeclaration field in owner.Fields.Where(field => field.Accessibility == CSharpAccessibility.Public && field.Type.RefKind == CSharpRefKind.None && !HasAttribute(field.Attributes, options.IgnoreAttributeName)))
			{
				if (field.IsStatic)
				{
					if (field.IsConst || field.IsReadOnly)
					{
						AppendFieldGetter(text, owner, field, enumUnderlyingTypes, isStatic: true);
					}
				}
				else
				{
					AppendFieldGetter(text, owner, field, enumUnderlyingTypes, isStatic: false);
					if (!field.IsConst && !field.IsReadOnly)
					{
						AppendFieldSetter(text, owner, field, enumUnderlyingTypes);
					}
				}
			}

			foreach (CSharpPropertyDeclaration property in owner.Properties.Where(property => property.Accessibility == CSharpAccessibility.Public && property.Type.RefKind == CSharpRefKind.None && !HasAttribute(property.Attributes, options.IgnoreAttributeName)))
			{
				if (property.IsStatic)
				{
					if (property.HasGetter && (!property.HasSetter || property.SetterAccessibility != CSharpAccessibility.Public) && property.GetterAccessibility == CSharpAccessibility.Public)
					{
						AppendPropertyGetter(text, owner, property, enumUnderlyingTypes, isStatic: true);
					}

					continue;
				}

				if (property.HasGetter && property.GetterAccessibility == CSharpAccessibility.Public)
				{
					AppendPropertyGetter(text, owner, property, enumUnderlyingTypes, isStatic: false);
				}

				if (property.HasSetter && !property.IsInitOnly && property.SetterAccessibility == CSharpAccessibility.Public)
				{
					AppendPropertySetter(text, owner, property, enumUnderlyingTypes);
				}
			}

			foreach (CSharpCallableDeclaration callable in owner.Callables.Where(callable => callable.Accessibility == CSharpAccessibility.Public && callable.Kind is CSharpCallableKind.Method or CSharpCallableKind.Constructor && !(owner.IsAbstract && callable.Kind == CSharpCallableKind.Constructor) && callable.TypeParameters.Count == 0 && !callable.IsAsync && callable.ReturnType.RefKind == CSharpRefKind.None && !HasAttribute(callable.Attributes, options.IgnoreAttributeName)))
			{
				AppendCallable(text, owner, callable, enumUnderlyingTypes);
			}
		}

		text.AppendLine("}");
		return text.ToString();
	}

	private static void AppendCallable(StringBuilder text, CSharpTypeDeclaration owner, CSharpCallableDeclaration callable, IReadOnlyDictionary<string, string> enumUnderlyingTypes)
	{
		string nativeName = callable.Kind == CSharpCallableKind.Constructor ? ConstructorNativeName(owner, callable.Parameters) : MemberIdentity(owner, callable.IsStatic ? 2 : 1, callable.Name, callable.Parameters.Select(parameter => parameter.Type).ToArray());
		CSharpTypeReference returnType = callable.Kind == CSharpCallableKind.Constructor ? HostType(owner, callable.Location) : callable.ReturnType;
		AppendMethodStart(text, nativeName, returnType, callable.Parameters, enumUnderlyingTypes, needsReceiver: callable.Kind != CSharpCallableKind.Constructor && !callable.IsStatic);
		AppendManagedLocals(text, callable.Parameters, enumUnderlyingTypes);
		string arguments = ManagedArguments(callable.Parameters);
		string invocation = callable.Kind == CSharpCallableKind.Constructor ? $"new {Target(owner)}({arguments})" : callable.IsStatic ? $"{Target(owner)}.{Identifier(callable.Name)}({arguments})" : $"(({Target(owner)})__receiver).{Identifier(callable.Name)}({arguments})";
		AppendInvocationAndReturn(text, returnType, invocation, enumUnderlyingTypes);
	}

	private static void AppendFieldGetter(StringBuilder text, CSharpTypeDeclaration owner, CSharpFieldDeclaration field, IReadOnlyDictionary<string, string> enumUnderlyingTypes, bool isStatic)
	{
		AppendMethodStart(text, MemberIdentity(owner, isStatic ? 7 : 6, field.Name, []), field.Type, [], enumUnderlyingTypes, !isStatic);
		string value = isStatic ? $"{Target(owner)}.{Identifier(field.Name)}" : $"(({Target(owner)})__receiver).{Identifier(field.Name)}";
		text.Append("\t\treturn ").Append(ToAot(value, field.Type, enumUnderlyingTypes)).AppendLine(";").AppendLine("\t}").AppendLine();
	}

	private static void AppendFieldSetter(StringBuilder text, CSharpTypeDeclaration owner, CSharpFieldDeclaration field, IReadOnlyDictionary<string, string> enumUnderlyingTypes)
	{
		CSharpParameterDeclaration value = new("value", field.Type, false, "", false, [], field.Location);
		AppendMethodStart(text, MemberIdentity(owner, 4, field.Name, [field.Type]), VoidType(field.Location), [value], enumUnderlyingTypes, needsReceiver: true);
		text.Append("\t\t((").Append(Target(owner)).Append(")__receiver).").Append(Identifier(field.Name)).Append(" = ").Append(FromAot("__arg0", field.Type, enumUnderlyingTypes)).AppendLine(";").AppendLine("\t}").AppendLine();
	}

	private static void AppendPropertyGetter(StringBuilder text, CSharpTypeDeclaration owner, CSharpPropertyDeclaration property, IReadOnlyDictionary<string, string> enumUnderlyingTypes, bool isStatic)
	{
		string nativeName = MemberIdentity(owner, isStatic ? 7 : 3, property.Name, property.Parameters.Select(parameter => parameter.Type).ToArray());
		AppendMethodStart(text, nativeName, property.Type, property.Parameters, enumUnderlyingTypes, !isStatic);
		AppendManagedLocals(text, property.Parameters, enumUnderlyingTypes);
		string target = isStatic ? Target(owner) : $"(({Target(owner)})__receiver)";
		string value = property.IsIndexer ? target + "[" + ManagedArguments(property.Parameters) + "]" : target + "." + Identifier(property.Name);
		text.Append("\t\treturn ").Append(ToAot(value, property.Type, enumUnderlyingTypes)).AppendLine(";").AppendLine("\t}").AppendLine();
	}

	private static void AppendPropertySetter(StringBuilder text, CSharpTypeDeclaration owner, CSharpPropertyDeclaration property, IReadOnlyDictionary<string, string> enumUnderlyingTypes)
	{
		CSharpParameterDeclaration value = new("value", property.Type, false, "", false, [], property.Location);
		CSharpParameterDeclaration[] parameters = property.Parameters.Append(value).ToArray();
		string nativeName = MemberIdentity(owner, 4, property.Name, parameters.Select(parameter => parameter.Type).ToArray());
		AppendMethodStart(text, nativeName, VoidType(property.Location), parameters, enumUnderlyingTypes, needsReceiver: true);
		AppendManagedLocals(text, parameters, enumUnderlyingTypes);
		string target = $"(({Target(owner)})__receiver)";
		if (property.IsIndexer)
		{
			target += "[" + string.Join(", ", Enumerable.Range(0, property.Parameters.Count).Select(index => $"__managed{index}")) + "]";
		}
		else
		{
			target += "." + Identifier(property.Name);
		}

		text.Append("\t\t").Append(target).Append(" = __managed").Append(parameters.Length - 1).AppendLine(";");
		text.AppendLine("\t}").AppendLine();
	}

	private static void AppendMethodStart(StringBuilder text, string nativeName, CSharpTypeReference returnType, IReadOnlyList<CSharpParameterDeclaration> parameters, IReadOnlyDictionary<string, string> enumUnderlyingTypes, bool needsReceiver)
	{
		text.Append("\tprivate static partial ").Append(AotType(returnType, enumUnderlyingTypes)).Append(' ').Append(HostMethodName(nativeName)).Append('(');
		bool comma = false;
		if (needsReceiver)
		{
			text.Append("object __receiver");
			comma = true;
		}

		for (int index = 0; index < parameters.Count; ++index)
		{
			if (comma)
			{
				text.Append(", ");
			}

			comma = true;
			text.Append(RefModifier(parameters[index].Type.RefKind)).Append(AotType(parameters[index].Type, enumUnderlyingTypes)).Append(" __arg").Append(index);
		}

		text.AppendLine(")").AppendLine("\t{");
	}

	private static void AppendManagedLocals(StringBuilder text, IReadOnlyList<CSharpParameterDeclaration> parameters, IReadOnlyDictionary<string, string> enumUnderlyingTypes)
	{
		for (int index = 0; index < parameters.Count; ++index)
		{
			CSharpTypeReference type = parameters[index].Type;
			if (type.RefKind != CSharpRefKind.None)
			{
				continue;
			}

			text.Append("\t\t").Append(SourceType(type)).Append(" __managed").Append(index).Append(" = ").Append(FromAot($"__arg{index}", type, enumUnderlyingTypes)).AppendLine(";");
		}
	}

	private static void AppendInvocationAndReturn(StringBuilder text, CSharpTypeReference returnType, string invocation, IReadOnlyDictionary<string, string> enumUnderlyingTypes)
	{
		if (returnType.DisplayName == "void")
		{
			text.Append("\t\t").Append(invocation).AppendLine(";");
		}
		else
		{
			text.Append("\t\t").Append(SourceType(returnType)).Append(" __result = ").Append(invocation).AppendLine(";");
		}

		if (returnType.DisplayName != "void")
		{
			text.Append("\t\treturn ").Append(ToAot("__result", returnType, enumUnderlyingTypes)).AppendLine(";");
		}

		text.AppendLine("\t}").AppendLine();
	}

	private static string ManagedArguments(IReadOnlyList<CSharpParameterDeclaration> parameters) => string.Join(", ", parameters.Select((parameter, index) => parameter.Type.RefKind switch
	{
		CSharpRefKind.Ref => $"ref __arg{index}",
		CSharpRefKind.Out => $"out __arg{index}",
		CSharpRefKind.In or CSharpRefKind.RefReadOnly => $"in __arg{index}",
		_ => $"__managed{index}"}));
	private static string AotType(CSharpTypeReference type, IReadOnlyDictionary<string, string> enumUnderlyingTypes)
	{
		if (type.Kind == CSharpTypeKind.Enum)
		{
			return ScalarAotType(enumUnderlyingTypes.GetValueOrDefault(type.QualifiedName, "int"));
		}

		if (type.TypeArguments.Count != 0)
		{
			string? container = ContainerName(type);
			if (container is not null)
			{
				return container + "<" + string.Join(", ", type.TypeArguments.Select(argument => AotType(argument, enumUnderlyingTypes))) + ">";
			}
		}

		return type.DisplayName switch
		{
			"void" => "void",
			"sbyte" => "sbyte",
			"byte" => "byte",
			"short" => "short",
			"ushort" or "char" => "ushort",
			"int" => "int",
			"uint" => "uint",
			"long" => "long",
			"ulong" => "ulong",
			"float" => "float",
			"double" => "double",
			"bool" => "bool",
			"string" => "VsString",
			_ => "object"
		};
	}

	private static string ScalarAotType(string type) => type switch
	{
		"sbyte" => "sbyte",
		"byte" => "byte",
		"short" => "short",
		"ushort" or "char" => "ushort",
		"uint" => "uint",
		"long" => "long",
		"ulong" => "ulong",
		_ => "int"
	};
	private static string FromAot(string value, CSharpTypeReference type, IReadOnlyDictionary<string, string> enumUnderlyingTypes)
	{
		if (type.Kind == CSharpTypeKind.Enum)
		{
			return $"({SourceType(type)})({value})";
		}
		return type.DisplayName switch
		{
			"string" => value + ".Value",
			"char" => "(char)(" + value + ")",
			"sbyte" or "byte" or "short" or "ushort" or "int" or "uint" or "long" or "ulong" or "float" or "double" or "bool" => value,
			_ => $"({SourceType(type)}){value}"};
	}

	private static string ToAot(string value, CSharpTypeReference type, IReadOnlyDictionary<string, string> enumUnderlyingTypes)
	{
		if (type.Kind == CSharpTypeKind.Enum)
		{
			return $"({AotType(type, enumUnderlyingTypes)})({value})";
		}

		return type.DisplayName switch
		{
			"string" => "new VsString(" + value + ")",
			"char" => "(ushort)(" + value + ")",
			_ => value
		};
	}

	private static string RefModifier(CSharpRefKind kind) => kind switch
	{
		CSharpRefKind.Ref or CSharpRefKind.Out => "ref ",
		CSharpRefKind.In or CSharpRefKind.RefReadOnly => "in ",
		_ => ""
	};
	private static string SourceType(CSharpTypeReference type) => type.DisplayName switch
	{
		"void" or "sbyte" or "byte" or "short" or "ushort" or "int" or "uint" or "long" or "ulong" or "float" or "double" or "bool" or "char" or "string" => type.DisplayName,
		_ => "global::" + type.QualifiedName
	};
	private static string HostMethodName(string nativeName) => "VsHost_" + Convert.ToHexString(Encoding.UTF8.GetBytes("member:" + nativeName));
	private static string MemberIdentity(CSharpTypeDeclaration owner, int kind, string name, IReadOnlyList<CSharpTypeReference> parameters)
	{
		string ownerName = owner.QualifiedName.Replace(".", "::", StringComparison.Ordinal);
		if (kind is 1 or 2)
		{
			// Match the core's canonical, UTF-8 length-framed method signature.
			string signature = "(" + string.Concat(parameters.Select(parameter =>
			{
				string type = NativeCanonicalType(parameter);
				type = parameter.RefKind switch
				{
					CSharpRefKind.Ref or CSharpRefKind.Out => "ref " + type,
					CSharpRefKind.In or CSharpRefKind.RefReadOnly => "const ref " + type,
					_ => type
				};
				return Encoding.UTF8.GetByteCount(type) + ":" + type;
			})) + ")";
			return "\u001Fhost." + ownerName + "." + name + "#" + Encoding.UTF8.GetByteCount(signature) + ":" + signature;
		}
		return ownerName + "::" + kind + "::" + name + "(" + string.Join(",", parameters.Select(parameter => NativeTypeNumber(parameter) + ":" + NativeHostName(parameter))) + ")";
	}
	private static int NativeTypeNumber(CSharpTypeReference type)
	{
		if (type.Kind == CSharpTypeKind.Array)
		{
			return 7;
		}
		if (type.TypeArguments.Count != 0)
		{
			string baseName = GenericBase(type);
			if (baseName == "System.Collections.Generic.List")
			{
				return 7;
			}
			if (baseName == "System.Collections.Generic.Dictionary")
			{
				return 8;
			}
			if (baseName == "System.Collections.Generic.HashSet")
			{
				return 9;
			}
			if (baseName == "System.Collections.Generic.Queue")
			{
				return 13;
			}
			if (baseName == "System.Collections.Generic.Stack")
			{
				return 14;
			}
			if (baseName == "System.Collections.Generic.SortedDictionary")
			{
				return 15;
			}
		}

		if (type.Kind == CSharpTypeKind.Enum)
		{
			return 12;
		}
		if (type.DisplayName is not ("void" or "sbyte" or "byte" or "short" or "ushort" or "char" or "int" or "uint" or "long" or "ulong" or "float" or "double" or "bool" or "string"))
		{
			return 6;
		}

		return type.DisplayName switch
		{
			"void" => 0,
			"int" => 1,
			"bool" => 2,
			"double" => 3,
			"string" => 4,
			"uint" => 5,
			"long" => 10,
			"ulong" => 11,
			"float" => 24,
			"sbyte" => 25,
			"byte" => 26,
			"short" => 27,
			"ushort" or "char" => 28,
			_ => 6
		};
	}

	private static string NativeHostName(CSharpTypeReference type) => type.Kind == CSharpTypeKind.Enum || NativeTypeNumber(type) == 6 ? type.QualifiedName.Replace(".", "::", StringComparison.Ordinal) : "";
	internal static string ConstructorNativeName(CSharpTypeDeclaration owner, IReadOnlyList<CSharpParameterDeclaration> parameters)
	{
		string ownerName = owner.QualifiedName.Replace(".", "::", StringComparison.Ordinal);
		string signature = "(" + string.Join(", ", parameters.Select(parameter =>
		{
			string type = NativeCanonicalType(parameter.Type);
			return parameter.Type.RefKind switch
			{
				CSharpRefKind.Ref or CSharpRefKind.Out => type + "&",
				CSharpRefKind.In or CSharpRefKind.RefReadOnly => "const " + type + "&",
				_ => type
			};
		})) + ")";
		return "\u001Fhostctor." + Encoding.UTF8.GetByteCount(ownerName) + ":" + ownerName + "." + Encoding.UTF8.GetByteCount(signature) + ":" + signature;
	}

	private static string NativeCanonicalType(CSharpTypeReference type)
	{
		if (type.Kind == CSharpTypeKind.Array && type.TypeArguments.Count == 1)
		{
			return "array<" + NativeCanonicalType(type.TypeArguments[0]) + ">";
		}

		if (type.TypeArguments.Count != 0)
		{
			string baseName = GenericBase(type);
			string? container = baseName switch
			{
				"System.Collections.Generic.List" => "array",
				"System.Collections.Generic.Dictionary" => "map",
				"System.Collections.Generic.SortedDictionary" => "ordered_map",
				"System.Collections.Generic.HashSet" => "set",
				"System.Collections.Generic.Queue" => "queue",
				"System.Collections.Generic.Stack" => "stack",
				_ => null
			};
			if (container is not null)
			{
				return container + "<" + string.Join(",", type.TypeArguments.Select(NativeCanonicalType)) + ">";
			}
		}

		if (type.Kind == CSharpTypeKind.Enum || type.Kind is CSharpTypeKind.Class or CSharpTypeKind.Struct && type.DisplayName is not ("sbyte" or "byte" or "short" or "ushort" or "char" or "int" or "uint" or "long" or "ulong" or "float" or "double" or "bool" or "string"))
		{
			return type.QualifiedName.Replace(".", "::", StringComparison.Ordinal);
		}

		return type.DisplayName switch
		{
			"sbyte" => "char",
			"byte" => "unsigned char",
			"short" => "short",
			"ushort" or "char" => "unsigned short",
			"uint" => "unsigned int",
			"long" => "int64",
			"ulong" => "uint64",
			_ => type.DisplayName
		};
	}

	private static CSharpTypeReference VoidType(CSharpSourceLocation location) => new("void", "void", CSharpTypeKind.Struct, false, 0, CSharpRefKind.None, [], location);
	private static CSharpTypeReference HostType(CSharpTypeDeclaration owner, CSharpSourceLocation location) => new(owner.Name, owner.QualifiedName, owner.Kind, false, 0, CSharpRefKind.None, [], location);
	private static string Target(CSharpTypeDeclaration type) => "global::" + type.QualifiedName;
	private static string Identifier(string value) => "@" + value;
	private static void ValidateAotType(CSharpTypeReference type, string owner, CSharpSourceLocation location, List<CSharpDiagnostic> diagnostics)
	{
		if (type.RefKind != CSharpRefKind.None && !IsDirectContainerElement(type))
		{
			diagnostics.Add(new(CSharpDiagnosticSeverity.Error, "VSCB3007", $"AOT bridge conversion for reference parameter '{type.DisplayName}' on '{owner}' cannot preserve shared reference storage; provide a manual partial bridge.", location));
			return;
		}

		if (type.Kind == CSharpTypeKind.Array)
		{
			diagnostics.Add(new(CSharpDiagnosticSeverity.Error, "VSCB3003", $"AOT bridge conversion for array type '{type.DisplayName}' on '{owner}' is not implemented; use List<T> or provide a manual partial bridge.", location));
			return;
		}

		if (type.TypeArguments.Count == 0)
		{
			return;
		}
		if (ContainerName(type)is null || type.TypeArguments.Any(argument => !IsDirectContainerElement(argument)))
		{
			diagnostics.Add(new(CSharpDiagnosticSeverity.Error, "VSCB3003", $"AOT bridge conversion for container type '{type.DisplayName}' on '{owner}' is not implemented for this element shape.", location));
		}
	}

	private static bool IsDirectContainerElement(CSharpTypeReference type)
	{
		if (type.Kind == CSharpTypeKind.Enum || type.Kind == CSharpTypeKind.Array || type.DisplayName is "string" or "char")
		{
			return false;
		}

		if (type.TypeArguments.Count != 0)
		{
			return ContainerName(type)is not null && type.TypeArguments.All(IsDirectContainerElement);
		}

		return type.DisplayName is "sbyte" or "byte" or "short" or "ushort" or "int" or "uint" or "long" or "ulong" or "float" or "double" or "bool";
	}

	private static void AddStructWriteBackDiagnostic(string member, CSharpSourceLocation location, List<CSharpDiagnostic> diagnostics) => diagnostics.Add(new(CSharpDiagnosticSeverity.Error, "VSCB3006", $"AOT bridge generation for mutable struct instance member '{member}' cannot preserve boxed receiver write-back; use a class or a static wrapper.", location));
	private static string? ContainerName(CSharpTypeReference type) => GenericBase(type) switch
	{
		"System.Collections.Generic.List" => "global::System.Collections.Generic.List",
		"System.Collections.Generic.Dictionary" => "global::System.Collections.Generic.Dictionary",
		"System.Collections.Generic.HashSet" => "global::System.Collections.Generic.HashSet",
		"System.Collections.Generic.Queue" => "global::System.Collections.Generic.Queue",
		"System.Collections.Generic.Stack" => "global::System.Collections.Generic.Stack",
		_ => null
	};
	private static string GenericBase(CSharpTypeReference type)
	{
		int open = type.QualifiedName.IndexOf('<', StringComparison.Ordinal);
		return open < 0 ? type.QualifiedName : type.QualifiedName[..open];
	}

	private static bool HasAttribute(IReadOnlyList<CSharpAttribute> attributes, string name) => attributes.Any(attribute => attribute.TypeName == name || attribute.TypeName.EndsWith("." + name, StringComparison.Ordinal));
}
